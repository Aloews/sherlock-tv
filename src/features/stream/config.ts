/**
 * Показывать ли ПОЛНЫЙ каталог каналов.
 *
 * ⚠️ ФЛАГ СБОРКИ, А НЕ ПРОВЕРКА ПРАВ, И ЭТО СОЗНАТЕЛЬНО. В игре каталог жил во
 * вкладке кабинета за `staffVerify` — проверкой пароля НА СЕРВЕРЕ. У этого
 * приложения сервера нет: любой пароль на клиенте лежит в бандле и открывается
 * просмотром исходников. В каталоге же 4081 запись, больше 1400 фильмов и
 * группа `♥18+` на 126 записей — притворяться дверью здесь нельзя.
 *
 * Поэтому выбор честный: публичная сборка каталога НЕ СОДЕРЖИТ, и обходить
 * нечего; оператору, которому нужно ответить на вопрос «почему в приложении
 * нет такого-то канала», собирают отдельный экземпляр с
 * VITE_SHOW_CATALOGUE=true.
 *
 * `import.meta.env` подставляется на сборке, поэтому при `false` Vite вырезает
 * и саму панель — это не спрятанный экран, а отсутствующий код.
 */
export function showCatalogue(): boolean {
  return import.meta.env.VITE_SHOW_CATALOGUE === 'true';
}
