// Порядок каналов и отсев мёртвых — ЧИСТАЯ часть: ни сети, ни окружения.
//
// ⚠️ ЗАЧЕМ ЭТО ПОНАДОБИЛОСЬ. Список из 31 канала выглядел рабочим, а «ТВ не
// работает» приходило всё равно. Замер по боевому плейлисту (25.08.2026,
// каждый канал дёрнут с `Origin:` боевого домена) объяснил почему:
//
//   Матч! Планета   404      ← сюда и идут за футболом
//   KHL             404
//   FUTBOL UZ       404
//   Arena Sport 3   не отвечает вовсе
//   NHL             200, но БЕЗ `access-control-allow-origin`
//   Sports Grid     200, без CORS
//   UNBEATEN        200, без CORS
//
// Семь из тридцати одного. Четыре мертвы совсем, ещё три отдают манифест, но
// без CORS — а hls.js берёт его через XHR, и без заголовка браузер ответ не
// отдаст. На iOS те же три играют (нативный HLS через `video.src` CORS не
// требует), то есть канал живой у одного зрителя и мёртвый у другого.
//
// Поэтому статического списка «плохих» здесь НЕТ и быть не может: он был бы
// враньём на половине устройств и протух бы через неделю. Мёртвое отсеивается
// по факту — плеер сообщает об отказе, экран помечает канал и уходит к
// следующему (см. `nextAlive`).
//
// Живёт это отдельным файлом без импортов из приложения — тем же приёмом, что
// `playlist.ts` и `fantasy/tactics.ts`.

import { pinRank, type Channel } from './playlist';
import type { Health } from './channelCache';

/**
 * Кого поднять наверх.
 *
 * Порядок ВНУТРИ списка значим: он и станет порядком в начале экрана. Совпадение
 * — по вхождению в название, без учёта регистра, потому что стабильного
 * идентификатора у канала в этом плейлисте нет вовсе: `tvg-id` проставлен у 166
 * записей из 4082 и ни одной спортивной, а числа в адресах принадлежат
 * конкретному ретранслятору и меняются вместе с ним.
 *
 * ⚠️ ЗДЕСЬ ТОЛЬКО ТЕ, ЧТО ПРОШЛИ ЗАМЕР. «Матч! Планета» просится в этот список
 * первой строкой и её здесь нет: на 25.08.2026 канал отдаёт 404. Поднять
 * мёртвый канал наверх — ровно тот баг, из-за которого «ТВ не работает»:
 * первый канал играет сам, и если он мёртв, сломанным выглядит всё.
 */
// Список закреплённых и `pinRank` живут в ./playlist: там же, где отбор.
// Один список решает и «показывать ли канал», и «каким по счёту» —
// два разошлись бы, и канал оказался бы закреплён, но невидим.

/**
 * Отсортировать: закреплённые в порядке PINNED, остальные — как в плейлисте.
 *
 * Сортировка УСТОЙЧИВАЯ (`Array.prototype.sort` таковой обязан быть начиная с
 * ES2019), и на это здесь опираются: у всех незакреплённых ранг одинаковый, и
 * порядок плейлиста между ними обязан сохраниться. Иначе список перетасовывался
 * бы на ровном месте при каждой загрузке.
 */
export function orderChannels(
  channels: readonly Channel[],
  health: Readonly<Record<string, Health>> = {},
  favourites: readonly string[] = [],
): Channel[] {
  // ⚠️ ИЗБРАННОЕ ВЫШЕ ЗДОРОВЬЯ. Здоровье — это то, что приложение УЗНАЛО;
  // избранное — то, что зритель СКАЗАЛ. Ставить догадку выше прямого указания
  // значит спорить с ним о том, что ему смотреть.
  const fav = new Set(favourites);
  // ⚠️ ЗДОРОВЬЕ ВАЖНЕЕ ЗАКРЕПЛЁННОСТИ, и это исправление моей же ошибки.
  // PINNED я составил по названиям, ни разу не проверив, играют ли каналы.
  // Замер прода 25.08.2026 по полной цепочке HLS: «Матч! Премьер», «Setanta
  // Sports 1 HD» и «Setanta Sports 2 HD» — все три МЕРТВЫ ниже первого
  // манифеста, и все три стояли первыми. Зритель упирался в три отказа подряд.
  //
  // PINNED по-прежнему решает, КАКИЕ каналы показывать и в каком порядке
  // среди равных. Но если канал уже отказал на этом устройстве — он уходит
  // вниз, каким бы закреплённым ни был, а игравший поднимается наверх.
  const bucket = (c: Channel) => {
    const h = health[c.url];
    if (h === 'played') return 0;
    if (h === 'failed') return 2;
    return 1;
  };
  return [...channels].sort((a, b) =>
    Number(fav.has(b.url)) - Number(fav.has(a.url))
    || bucket(a) - bucket(b)
    || pinRank(a) - pinRank(b));
}

/**
 * Следующий канал, который ЕЩЁ НЕ ОТКАЗАЛ.
 *
 * Это и есть починка «ТВ не работает». Раньше отказавший канал просто показывал
 * `stream.error` и на этом всё заканчивалось — а отказывает каждый четвёртый.
 * Теперь экран идёт дальше по списку, начиная со следующего за текущим, и
 * возвращается к началу: мёртвый канал стоит зрителю не вечера, а секунды.
 *
 * `null` — живых не осталось. Это НЕ то же самое, что «список пуст», и экран
 * обязан сказать разное: «все каналы сегодня недоступны» против «каналов нет».
 */
export function nextAlive(
  channels: readonly Channel[],
  currentUrl: string | null,
  dead: ReadonlySet<string>,
): string | null {
  if (channels.length === 0) return null;
  const from = channels.findIndex((c) => c.url === currentUrl);
  // Текущего в списке нет (плейлист обновился) — начинаем с начала, а не с -1.
  const start = from === -1 ? 0 : from + 1;
  for (let step = 0; step < channels.length; step += 1) {
    const candidate = channels[(start + step) % channels.length];
    if (!dead.has(candidate.url)) return candidate.url;
  }
  return null;
}

/**
 * Отбор для списка: поиск по названию и «только избранное».
 *
 * Поиск по ВХОЖДЕНИЮ и без учёта регистра: зритель печатает «сет», а канал
 * называется «Setanta Sports 1 HD». Требовать совпадения с начала значило бы
 * заставлять его знать, как именно записан канал в чужом плейлисте.
 *
 * Порядок НЕ трогается: сортировка уже сделана `orderChannels`, и
 * пересортировать результат поиска значило бы показать избранное и рабочее
 * не там, где зритель их только что видел.
 */
export function filterChannels(
  channels: readonly Channel[],
  query: string,
  favouritesOnly: boolean,
  favourites: readonly string[] = [],
): Channel[] {
  const q = query.trim().toLowerCase();
  const fav = new Set(favourites);
  return channels.filter((c) => {
    if (favouritesOnly && !fav.has(c.url)) return false;
    if (!q) return true;
    return c.name.toLowerCase().includes(q);
  });
}
