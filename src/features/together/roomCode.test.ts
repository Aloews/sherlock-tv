import { describe, it, expect } from 'vitest';
import { isValidRoomCode, makeRoomCode, normalizeRoomCode } from './roomCode';

/**
 * КОД КОМНАТЫ — ЭТО КЛЮЧ ОТ НЕЁ, и проверяется он как ключ.
 *
 * Проверить, кто стучится, релею нечем: подпись Telegram приходит только
 * приложениям с сервером бота, а у этого его нет. Значит, угадываемый код —
 * это открытая дверь, и «код генерируется случайно» здесь не пожелание, а
 * единственная мера.
 */
describe('makeRoomCode', () => {
  it('не повторяется на тысяче вызовов', () => {
    const seen = new Set<string>();
    for (let i = 0; i < 1000; i += 1) seen.add(makeRoomCode());
    expect(seen.size).toBe(1000);
  });

  it('годится для релея — иначе выдача отвергнет собственный код', () => {
    for (let i = 0; i < 200; i += 1) expect(isValidRoomCode(makeRoomCode())).toBe(true);
  });

  // ⚠️ ЭТО НЕ ПРИДИРКА К ШРИФТУ. Код диктуют голосом и переписывают из
  // сообщения: 0/o и 1/l/i в такой передаче — промах алфавита, а не опечатка
  // зрителя. Проверка смотрит на КАЖДЫЙ символ тысячи кодов: одна забытая
  // буква в алфавите иначе всплыла бы у зрителя, а не здесь.
  it('не содержит похожих друг на друга символов', () => {
    const confusable = /[01loiuv]/;
    for (let i = 0; i < 1000; i += 1) {
      expect(makeRoomCode()).not.toMatch(confusable);
    }
  });

  // Десять символов из двадцати девяти — около 48 бит. Перебор комнат при
  // этом стоит дороже, чем что бы то ни было за ними.
  it('длиной в десять символов', () => {
    expect(makeRoomCode()).toHaveLength(10);
  });
});

describe('normalizeRoomCode', () => {
  it('обрезает пробелы и опускает регистр — как это делает релей', () => {
    expect(normalizeRoomCode('  ABC-123  ')).toBe('abc-123');
  });
});

/**
 * ⚠️ ПРАВИЛО ОБЯЗАНО СОВПАДАТЬ С СЕРВЕРНЫМ (`stream-service/livekit.js`).
 * Разойдись они — приложение отправляло бы код, который релей отвергает, и
 * зритель видел бы «ошибка» вместо «такой код не годится».
 */
describe('isValidRoomCode', () => {
  it.each(['abc', 'abc-123', 'match-1', 'a'.repeat(48)])('принимает %j', (code) => {
    expect(isValidRoomCode(code)).toBe(true);
  });

  it.each([
    '',                // пусто
    'ab',              // короче трёх
    '-abc',            // начинается с дефиса
    'ABC',             // верхний регистр — канон опускает его ДО проверки
    'код-комнаты',     // кириллица
    'a b',             // пробел
    'a_b',             // подчёркивание
    'a'.repeat(49),    // длиннее сорока восьми
  ])('отвергает %j', (code) => {
    expect(isValidRoomCode(code)).toBe(false);
  });
});
