/**
 * Код комнаты совместного просмотра.
 *
 * ⚠️ КОД — ЭТО И ЕСТЬ КЛЮЧ ОТ КОМНАТЫ, И ПОТОМУ ОН СЛУЧАЙНЫЙ. Проверить, кто
 * стучится, релею нечем: Telegram отдаёт подпись только приложениям, у которых
 * есть сервер бота, а у этого приложения сервера нет вовсе. Значит, пропуск
 * получает всякий, кто знает код, — и «match1», «real-barca», «vasya» это
 * открытая дверь, которую подберут перебором за минуты.
 *
 * Десять символов из тридцати двух — это 50 бит. Придумывать код руками
 * приложение не предлагает нигде: ввести чужой (полученный от друга) можно,
 * сочинить свой — нет.
 *
 * ⚠️ АЛФАВИТ БЕЗ ПОХОЖИХ БУКВ. Код диктуют голосом и переписывают из
 * сообщения: `0`/`o`, `1`/`l`/`i` в такой передаче — это не опечатка зрителя,
 * а промах алфавита. Выброшены и `u` с `v` — в рукописном виде они сливаются.
 *
 * Правило совпадает с серверным (`stream-service/livekit.js`): нижний
 * регистр, цифры и дефис, от 3 до 48 символов, первый символ не дефис.
 * Расходиться им нельзя — тогда приложение отправляло бы код, который релей
 * отвергнет, и зритель видел бы «ошибка» вместо «такой код не годится».
 */

const ALPHABET = 'abcdefghjkmnpqrstwxyz23456789';
const LENGTH = 10;

const PATTERN = /^[a-z0-9][a-z0-9-]{2,47}$/;

/** Новый код комнаты — случайный, из системного источника случайности. */
export function makeRoomCode(): string {
  // ⚠️ crypto, А НЕ Math.random. Код — ключ; Math.random предсказуем по
  // выданным значениям, и это не теория: генераторы браузеров для того и не
  // годятся, поэтому у них есть отдельный криптографический.
  const bytes = new Uint8Array(LENGTH);
  crypto.getRandomValues(bytes);
  let out = '';
  for (const b of bytes) out += ALPHABET[b % ALPHABET.length];
  return out;
}

/** Приводит введённое к канону: обрезает пробелы и опускает регистр. */
export function normalizeRoomCode(raw: string): string {
  return raw.trim().toLowerCase();
}

export function isValidRoomCode(code: string): boolean {
  return PATTERN.test(code);
}
