/**
 * Знак MatchLive: мяч, внутри — треугольник воспроизведения.
 *
 * ⚠️ СВОЙ SVG, А НЕ ИКОНКА ИЗ БИБЛИОТЕКИ. Раньше в заголовке стоял
 * `IconDeviceTv` из tabler — та же картинка, что у тысячи приложений, и
 * логотипом она не была. Знак рисуется двумя фигурами, поэтому одинаково
 * читается и в заголовке, и в 16 пикселях вкладки: окружность — мяч,
 * треугольник — «идёт эфир».
 *
 * `currentColor` у обеих фигур: цвет задаёт место, куда знак поставили, и
 * тогда он работает и на тёмном фоне заголовка, и в любом другом.
 */
export function Logo({ size = 26, className = '' }: { size?: number; className?: string }) {
  return (
    <svg
      width={size} height={size} viewBox="0 0 32 32"
      fill="none" className={className} aria-hidden="true" focusable="false"
    >
      <circle cx="16" cy="16" r="13" stroke="currentColor" strokeWidth="2.5" />
      {/* Треугольник сдвинут на пиксель вправо: оптический центр круга правее
          геометрического, и по геометрии знак смотрится заваленным влево. */}
      <path d="M13.5 10.5 L23 16 L13.5 21.5 Z" fill="currentColor" />
    </svg>
  );
}

